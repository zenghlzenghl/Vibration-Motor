/**
 * @brief 自动关机时间 (毫秒)
 *
 * 系统在以下条件**同时满足**时，经过此时间后自动关机：
 * 1. 系统处于ON状态
 * 2. 无充电器连接
 * 3. 马达处于IDLE模式
 * 4. 无任何用户操作
 *
 * @note 取值建议：
 *       - 60000 (1分钟): 测试用，快速验证自动关机功能
 *       - 300000 (5分钟): **推荐**，平衡省电和便利性
 *       - 600000 (10分钟): 更长的使用时间
 *       - 0: **禁用自动关机功能**
 *
 * @warning 设为0时会禁用自动关机，可能导致电池耗尽！
 */
#define AUTO_POWEROFF_TIME_MS       300000UL

/**
 * @brief 开机确认振动时间 (毫秒)
 *
 * 用户长按开机后，马达会振动此时间长度
 * 作为"已开机"的触觉反馈。
 *
 * @note 取值建议：
 *       - 30ms: 微弱提示，几乎感觉不到
 *       - 50ms: **推荐**，清晰但不突兀
 *       - 100ms: 明显提示
 *       - 200ms: 强烈提示（可能过于扰人）
 */
#define STARTUP_VIBRATION_MS        50

