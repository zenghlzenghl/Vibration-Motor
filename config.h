/**
 * @defgroup GPIO_Config GPIO引脚配置
 * @brief 定义各功能模块使用的GPIO引脚
 * @{
 */

/**
 * @brief 按键输入引脚
 *
 * 连接物理按键，低电平有效（按下=GND）
 * 必须配置为内部上拉输入模式
 *
 * @note 硬件要求：
 *       - 按键一端接此引脚，另一端接GND
 *       - 按下时引脚电平为LOW
 *       - 释放时引脚电平为HIGH（上拉）
 *
 * @warning 此引脚必须支持外部中断(INT0)
 */
#define BUTTON_PIN                  GPIO_PIN_0

/**
 * @brief LED指示灯引脚
 *
 * 连接LED，高电平点亮
 * 配置为推挽输出模式
 *
 * @note 硬件连接：
 *       P0.2 → [限流电阻220Ω~1kΩ] → LED阳极 → LED阴极 → GND
 *       高电平 = LED亮，低电平 = LED灭
 */
#define LED_PIN                     GPIO_PIN_2

/**
 * @brief 马达控制引脚
 *
 * 连接MOSFET栅极(Gate)，高电平开启马达
 * 配置为推挽输出模式
 *
 * @note 驱动电路：
 *       P0.3 → [1kΩ电阻] → MOSFET Gate
 *       MOSFET Source → GND
 *       MOSFET Drain → 马达(-)
 *       马达(+) → VCC(Battery)
 *
 * @warning 需要N沟道增强型MOSFET（如AO3400A）
 */
#define MOTOR_PIN                   GPIO_PIN_3

/**
 * @brief 充电器检测引脚
 *
 * 经过外部分压电阻后的充电器电压
 * **不需要**配置内部上下拉（由外部电路决定电平）
 *
 * @note 分压电路：
 *       Charger_VCC(5V) → [R1:10K] → P0.5 → [R2:10K] → GND
 *       插入充电器: P0.5 ≈ 2.5V (HIGH)
 *       拔出充电器: P0.5 = 0V (LOW)
 *
 * @warning 切勿对此引脚使能内部上下拉！
 */
#define CHARGER_DETECT_PIN          GPIO_PIN_5

/**
 * @brief 充电状态检测引脚
 *
 * 连接充电管理IC的状态输出引脚
 * 需要配置为内部上拉输入
 *
 * @note 电平定义：
 *       LOW  = 正在充电中
 *       HIGH = 电池已充满
 *
 * @note 典型IC：TP4056, MCP73831等
 */
#define CHARGE_STATUS_PIN           GPIO_PIN_1

/** @} */ /* end of GPIO_Config */

