/**
 * @defgroup Button_Config 按键配置参数
 * @{
 */

/**
 * @brief 软件消抖时间 (毫秒)
 *
 * 机械按键在按下/释放瞬间会产生抖动（10~20ms的多次跳变）
 * 此参数定义需要忽略的抖动持续时间。
 *
 * @note 取值建议：
 *       - 10ms: 响应快，但对质量差的按键可能误触
 *       - 20ms: 推荐，平衡响应速度和稳定性
 *       - 50ms: 最稳定，但感觉迟钝
 *
 * @see BUTTON_LONG_PRESS_MS
 */
#define BUTTON_DEBOUNCE_MS          20

/**
 * @brief 长按判定阈值 (毫秒)
 *
 * 按键持续按下超过此时间判定为"长按"
 * 否则判定为"短按"
 *
 * @note 取值建议：
 *       - 1000ms (1秒): 快速操作，易误触
 *       - 1500ms (1.5秒): **推荐**，用户体验好
 *       - 2000ms (2秒): 稳定，但手指易疲劳
 *       - 3000ms (3秒): 防误触，适合关键操作
 *
 * @see BUTTON_DEBOUNCE_MS
 */
#define BUTTON_LONG_PRESS_MS        1500

/** @} */ /* end of Button_Config */

