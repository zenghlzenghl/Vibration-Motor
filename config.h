/**
 * @brief CPU时钟频率 (Hz)
 *
 * 定义系统主时钟频率，用于计算定时器重载值。
 *
 * @note 常用取值：
 *       - 12000000UL (12.0 MHz)  - 默认值，通用性强
 *       - 11059200UL (11.0592MHz) - 串口通信常用（波特率精确）
 *       - 8000000UL  (8.0 MHz)   - 低功耗应用
 *       - 16000000UL (16.0 MHz)  - 高性能需求
 *
 * @warning 修改此值后，TIMER0_RELOAD_H/L 会自动适配，
 *          无需手动计算！但需确保硬件晶振匹配。
 */
#define F_CPU                       12000000UL

/**
 * @brief Timer0 重载值（高字节）
 *
 * 根据F_CPU自动计算，用于1ms精确定时。
 *
 * @note 计算公式：
 *       重载值 = 65536 - (F_CPU / 12 / 1000)
 *       其中：12是8051的机器周期系数
 *             1000是目标定时时间(1ms)
 *
 * 示例（12MHz）：
 *       重载值 = 65536 - (12000000 / 12 / 1000)
 *              = 65536 - 1000
 *              = 64536
 *              = 0xFC18
 *              → H=0xFC, L=0x18
 */
#if (F_CPU == 12000000UL)
    #define TIMER0_RELOAD_H         0xFC
    #define TIMER0_RELOAD_L         0x18

#elif (F_CPU == 11059200UL)
    /**
     * @brief 11.0592MHz对应的Timer重载值
     * @note  此频率下波特率更精确，常用于串口通信项目
     */
    #define TIMER0_RELOAD_H         0xFC
    #define TIMER0_RELOAD_L         0x66

#else
    /**
     * @error 不支持的时钟频率
     * @note  如果需要使用其他频率，请参照上面的公式计算
     *        并添加新的 #elif 分支
     */
    #error "Unsupported CPU frequency, please define F_CPU"
#endif

